BEGIN;
CREATE TABLE departments (
 dept_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 dept_code varchar(20) NOT NULL UNIQUE, name varchar(150) NOT NULL);
CREATE TABLE students (
 student_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(150) NOT NULL, email varchar(254) NOT NULL UNIQUE,
 batch integer NOT NULL CHECK(batch BETWEEN 1900 AND 2200),
 dept_id integer NOT NULL REFERENCES departments);
CREATE TABLE teachers (
 teacher_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 full_name varchar(150) NOT NULL, email varchar(254) NOT NULL UNIQUE,
 dept_id integer NOT NULL REFERENCES departments);
CREATE TABLE courses (
 course_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_code varchar(20) NOT NULL UNIQUE, title varchar(150) NOT NULL,
 credits numeric(4,1) NOT NULL CHECK(credits > 0 AND credits <> 'NaN'),
 dept_id integer NOT NULL REFERENCES departments);
CREATE TABLE course_offerings (
 offering_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 course_id integer NOT NULL REFERENCES courses, teacher_id integer NOT NULL REFERENCES teachers,
 semester varchar(20) NOT NULL CHECK(semester IN ('Spring','Summer','Fall')),
 year integer NOT NULL CHECK(year BETWEEN 1900 AND 2200),
 section varchar(20) NOT NULL, capacity integer NOT NULL CHECK(capacity > 0),
 status varchar(20) NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','open','closed','completed')),
 UNIQUE(course_id,year,semester,section));
CREATE TABLE prerequisites (
 course_id integer REFERENCES courses, prereq_course_id integer REFERENCES courses,
 minimum_grade_point numeric(3,2) NOT NULL DEFAULT 2 CHECK(minimum_grade_point BETWEEN 0 AND 4),
 PRIMARY KEY(course_id, prereq_course_id), CHECK(course_id <> prereq_course_id));
CREATE TABLE enrollments (
 enrollment_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 student_id integer NOT NULL REFERENCES students, offering_id integer NOT NULL REFERENCES course_offerings,
 status varchar(20) NOT NULL DEFAULT 'enrolled', grade_point numeric(3,2),
 enrolled_at timestamptz NOT NULL DEFAULT now(), UNIQUE(student_id, offering_id),
 CONSTRAINT enrollment_grade_state CHECK(
 (status IN ('enrolled','dropped') AND grade_point IS NULL) OR
 (status='completed' AND grade_point IS NOT NULL AND grade_point BETWEEN 0 AND 4)));
CREATE TABLE enrollment_audit (
 audit_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
 enrollment_id bigint NOT NULL REFERENCES enrollments,
 action varchar(20) NOT NULL CHECK(action IN ('ENROLLED','WITHDRAWN')),
 action_time timestamptz NOT NULL DEFAULT now());
CREATE TABLE users (
 user_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, email varchar(254) NOT NULL,
 password_hash text NOT NULL, role varchar(20) NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','active','rejected','disabled')),
 student_id integer UNIQUE REFERENCES students, teacher_id integer UNIQUE REFERENCES teachers,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT linked_identity CHECK(
 (role='student' AND student_id IS NOT NULL AND teacher_id IS NULL) OR
 (role='teacher' AND teacher_id IS NOT NULL AND student_id IS NULL) OR
 (role='admin' AND student_id IS NULL AND teacher_id IS NULL)));
CREATE UNIQUE INDEX users_login ON users(lower(email));
CREATE INDEX enrollment_occupancy ON enrollments(offering_id,status);
CREATE INDEX offering_teacher ON course_offerings(teacher_id);
CREATE INDEX offering_term ON course_offerings(year,semester,status);
CREATE INDEX audit_enrollment ON enrollment_audit(enrollment_id);
CREATE INDEX students_department ON students(dept_id);
CREATE INDEX teachers_department ON teachers(dept_id);
CREATE INDEX courses_department ON courses(dept_id);
CREATE INDEX prerequisite_reverse ON prerequisites(prereq_course_id);

CREATE VIEW student_gpa AS
 SELECT s.student_id,coalesce(sum(c.credits),0) graded_credits,
 round(sum(c.credits*e.grade_point)/nullif(sum(c.credits),0),2) gpa
 FROM students s LEFT JOIN enrollments e ON e.student_id=s.student_id AND e.status='completed'
 LEFT JOIN course_offerings o USING(offering_id) LEFT JOIN courses c USING(course_id)
 GROUP BY s.student_id;

CREATE VIEW offering_enrollment_summary AS
 SELECT o.*,c.course_code,c.title,c.credits,c.dept_id,d.dept_code,t.full_name AS teacher,
 count(e.enrollment_id) AS occupied_seats,o.capacity-count(e.enrollment_id) AS remaining_seats
 FROM course_offerings o JOIN courses c USING(course_id) JOIN departments d USING(dept_id)
 JOIN teachers t USING(teacher_id) LEFT JOIN enrollments e ON e.offering_id=o.offering_id AND e.status <> 'dropped'
 GROUP BY o.offering_id,c.course_id,d.dept_id,t.teacher_id;

CREATE FUNCTION log_enrollment() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
   INSERT INTO enrollment_audit(enrollment_id,action) VALUES(NEW.enrollment_id,'ENROLLED');
 ELSIF NEW.status='dropped' AND OLD.status <> 'dropped' THEN
   INSERT INTO enrollment_audit(enrollment_id,action) VALUES(NEW.enrollment_id,'WITHDRAWN');
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER enrollment_event AFTER INSERT OR UPDATE ON enrollments
 FOR EACH ROW EXECUTE FUNCTION log_enrollment();

CREATE FUNCTION register_student(s integer, target integer) RETURNS text LANGUAGE plpgsql
 SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE o course_offerings%ROWTYPE;
BEGIN
 PERFORM 1 FROM students WHERE student_id=s FOR UPDATE;
 IF NOT FOUND THEN RETURN 'STUDENT_NOT_FOUND'; END IF;
 SELECT * INTO o FROM course_offerings WHERE offering_id=target FOR UPDATE;
 IF NOT FOUND THEN RETURN 'OFFERING_NOT_FOUND'; END IF;
 IF o.status <> 'open' THEN RETURN 'OFFERING_NOT_OPEN'; END IF;
 PERFORM 1 FROM courses WHERE course_id=o.course_id FOR SHARE;
 IF EXISTS(SELECT FROM enrollments WHERE student_id=s AND offering_id=target) THEN RETURN 'ALREADY_REGISTERED'; END IF;
 IF EXISTS(SELECT FROM enrollments e JOIN course_offerings x USING(offering_id)
   WHERE e.student_id=s AND e.status <> 'dropped' AND (x.course_id,x.year,x.semester)=(o.course_id,o.year,o.semester))
 THEN RETURN 'COURSE_ALREADY_TAKEN_THIS_TERM'; END IF;
 IF EXISTS(SELECT FROM prerequisites p WHERE p.course_id=o.course_id AND NOT EXISTS(
   SELECT FROM enrollments e JOIN course_offerings x USING(offering_id) WHERE e.student_id=s AND
   x.course_id=p.prereq_course_id AND e.status='completed' AND e.grade_point>=p.minimum_grade_point))
 THEN RETURN 'PREREQUISITE_NOT_SATISFIED'; END IF;
 IF (SELECT count(*) FROM enrollments WHERE offering_id=target AND status <> 'dropped')>=o.capacity
 THEN RETURN 'OFFERING_FULL'; END IF;
 INSERT INTO enrollments(student_id,offering_id) VALUES(s,target);
 RETURN 'REGISTERED';
END $$;

CREATE FUNCTION withdraw_student(s integer,target integer) RETURNS text LANGUAGE plpgsql
 SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE state text;
BEGIN
 PERFORM 1 FROM students WHERE student_id=s FOR UPDATE;
 IF NOT FOUND THEN RETURN 'STUDENT_NOT_FOUND'; END IF;
 SELECT status INTO state FROM course_offerings WHERE offering_id=target FOR UPDATE;
 IF NOT FOUND THEN RETURN 'OFFERING_NOT_FOUND'; END IF;
 IF state <> 'open' THEN RETURN 'OFFERING_NOT_OPEN'; END IF;
 UPDATE enrollments SET status='dropped' WHERE student_id=s AND offering_id=target AND status='enrolled';
 IF NOT FOUND THEN RETURN 'NO_ACTIVE_ENROLLMENT'; END IF;
 RETURN 'WITHDRAWN';
END $$;

CREATE FUNCTION submit_grade(t integer, eid bigint, grade numeric) RETURNS text LANGUAGE plpgsql
 SECURITY DEFINER SET search_path=pg_catalog,public,pg_temp AS $$
DECLARE o course_offerings%ROWTYPE;
BEGIN
 SELECT x.* INTO o FROM course_offerings x JOIN enrollments e USING(offering_id)
 WHERE e.enrollment_id=eid FOR UPDATE OF x;
 IF NOT FOUND OR o.teacher_id IS DISTINCT FROM t THEN RETURN 'UNAUTHORIZED'; END IF;
 IF grade IS NULL OR grade NOT BETWEEN 0 AND 4 OR grade<>round(grade,2) THEN RETURN 'INVALID_GRADE'; END IF;
 UPDATE enrollments SET grade_point=grade,status='completed' WHERE enrollment_id=eid AND
 ((o.status='closed' AND status IN ('enrolled','completed')) OR (o.status='completed' AND status='completed'));
 IF NOT FOUND THEN RETURN 'NOT_GRADABLE'; END IF;
 RETURN 'GRADED';
END $$;

CREATE FUNCTION protect_offering() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='INSERT' THEN
   IF NEW.status <> 'draft' THEN RAISE EXCEPTION 'Create offerings as drafts' USING ERRCODE='23514'; END IF;
   RETURN NEW;
 END IF;
 IF NEW.status<>OLD.status AND (OLD.status,NEW.status) NOT IN
 (('draft','open'),('open','closed'),('closed','completed')) THEN
 RAISE EXCEPTION 'Invalid offering transition' USING ERRCODE='23514'; END IF;
 IF NEW.status='completed' AND EXISTS(SELECT FROM enrollments WHERE offering_id=OLD.offering_id AND status='enrolled')
 THEN RAISE EXCEPTION 'Unresolved grades' USING ERRCODE='23514'; END IF;
 IF NEW.capacity < (SELECT count(*) FROM enrollments WHERE offering_id=OLD.offering_id AND status<>'dropped')
 THEN RAISE EXCEPTION 'Capacity below occupancy' USING ERRCODE='23514'; END IF;
 IF (NEW.course_id,NEW.year,NEW.semester,NEW.section,NEW.teacher_id) IS DISTINCT FROM
 (OLD.course_id,OLD.year,OLD.semester,OLD.section,OLD.teacher_id) AND EXISTS(
 SELECT FROM enrollments WHERE offering_id=OLD.offering_id)
 THEN RAISE EXCEPTION 'Offering already has academic history' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER offering_guard BEFORE INSERT OR UPDATE ON course_offerings FOR EACH ROW EXECUTE FUNCTION protect_offering();

CREATE FUNCTION protect_course() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF (NEW.credits,NEW.course_code) IS DISTINCT FROM (OLD.credits,OLD.course_code) AND EXISTS(
 SELECT FROM enrollments JOIN course_offerings USING(offering_id) WHERE course_id=OLD.course_id)
 THEN RAISE EXCEPTION 'Course already has academic history' USING ERRCODE='23514'; END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER course_guard BEFORE UPDATE ON courses FOR EACH ROW EXECUTE FUNCTION protect_course();

